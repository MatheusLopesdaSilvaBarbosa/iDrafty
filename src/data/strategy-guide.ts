export const GUIDE_SCORING_RULES = {
  meta: 4,
  subMeta: 2,
  lastPickWarning: -2,
  mapHighlight: 4,
  worstMap: -4,
  counterAdvantage: 2,
  hardCounterAdvantage: 5,
  countered: -2,
  hardCounter: -5,
  teamSynergy: 1,
  support: 2,
} as const;

const LAST_PICK_LAUNCHERS = new Set([
  "barley",
  "dynamike",
  "grom",
  "tick",
  "sprout",
  "willow",
  "juju",
  "larry-lawrie",
  "berry",
  "squeak",
]);

export function getGuideEntry(id: string): GuideEntry | undefined {
  return GUIDE_BY_BRAWLER_ID[id];
}

export function getMatchupGuideEntry(id: string): GuideEntry | undefined {
  return getGuideEntry(id);
}

export function getGuideCounterTargets(id: string): string[] {
  return Object.values(GUIDE_BY_BRAWLER_ID)
    .filter((entry) => entry.counteredBy.includes(id))
    .map((entry) => entry.id);
}

export function getGuideHardCounterTargets(id: string): string[] {
  return Object.values(GUIDE_BY_BRAWLER_ID)
    .filter((entry) => entry.hardCounters.includes(id))
    .map((entry) => entry.id);
}

export function getAvailableHardCounters(
  id: string,
  unavailableIds: ReadonlySet<string>,
): string[] {
  return (getMatchupGuideEntry(id)?.hardCounters ?? []).filter(
    (counterId) => counterId && !unavailableIds.has(counterId),
  );
}

export function getDraftWarning(id: string, role?: string, range?: string): string | null {
  const entry = GUIDE_BY_BRAWLER_ID[id];
  const individual = entry?.warning?.trim();
  if (individual && !individual.startsWith("Sem alerta geral")) return individual;
  if (LAST_PICK_LAUNCHERS.has(id)) {
    return "Possível last pick: lançador vulnerável a mergulhos, mobilidade ou pressão de longo alcance. Confira o mapa e os picks inimigos.";
  }
  if (role === "Assassino" || (role === "Tanque" && range === "curto")) {
    return "Possível last pick: o adversário ainda pode responder com controle, empurrões, mobilidade ou dano antitanque. Avalie o draft antes de escolher cedo.";
  }
  return null;
}

export function getGuideBadges(
  id: string,
  role?: string,
  range?: string,
  tier?: { meta?: boolean; subMeta?: boolean },
): string[] {
  const entry = GUIDE_BY_BRAWLER_ID[id];
  const badges: string[] = [];
  if (tier?.meta ?? entry?.meta) badges.push("🌟 META");
  else if (tier?.subMeta ?? entry?.subMeta) badges.push("✨ SUB-META");
  if (getDraftWarning(id, role, range)) badges.push("⚠ LAST PICK");
  return badges;
}
