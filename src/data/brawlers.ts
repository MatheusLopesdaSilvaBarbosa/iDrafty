const RARITY_BY_ID = new Map<string, BrawlerRarity>([
  ...Object.entries(RARITY_IDS).flatMap(([rarity, ids]) =>
    ids.map((id) => [id, rarity as BrawlerRarity] as const),
  ),
  ["lightyear-indisponivel", "Indisponível"] as const,
]);
function rarityFor(id: string): BrawlerRarity {
  return RARITY_BY_ID.get(id) ?? "Indisponível";
}

type L = Level;
function b(
  id: string,
  name: string,
  role: Role,
  range: RangeClass,
  [mobility, durability, damage, areaControl, crowdControl, pressure]: [L, L, L, L, L, L],
  provides: string[],
  weakTo: string[],
  goodModes: ModeId[],
  strengths: string[],
  weaknesses: string[],
  dependsOn: Brawler["dependsOn"] = [],
): Brawler {
  return {
    id,
    name,
    role,
    range,
    rarity: rarityFor(id),
    mobility,
    durability,
    damage,
    areaControl,
    crowdControl,
    pressure,
    provides,
    weakTo,
    goodModes,
    strengths,
    weaknesses,
    dependsOn,
    status: "estimativa",
    updated: UPDATED,
    available: true,
    imageAlias: name === "Corvo" ? "Crow" : name === "Eugênio" ? "Gene" : name,
  };
}

